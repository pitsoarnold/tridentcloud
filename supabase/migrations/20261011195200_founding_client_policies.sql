CREATE TABLE IF NOT EXISTS public.founding_client_config (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  is_active boolean NOT NULL DEFAULT true,
  total_spots integer NOT NULL DEFAULT 10 CHECK (total_spots > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.founding_client_config
  ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS total_spots integer NOT NULL DEFAULT 10;

CREATE TABLE IF NOT EXISTS public.founding_client_applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  email text NOT NULL,
  business_name text,
  preferred_tier text NOT NULL CHECK (
    preferred_tier IN ('presence', 'digital-office', 'digital-sales', 'unsure')
  ),
  message text,
  status text NOT NULL DEFAULT 'new',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS founding_client_applications_status_idx
  ON public.founding_client_applications (status);

ALTER TABLE public.founding_client_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.founding_client_applications ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
  existing_policy record;
BEGIN
  FOR existing_policy IN
    SELECT policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'founding_client_config'
  LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON public.founding_client_config',
      existing_policy.policyname
    );
  END LOOP;

  FOR existing_policy IN
    SELECT policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'founding_client_applications'
  LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON public.founding_client_applications',
      existing_policy.policyname
    );
  END LOOP;
END;
$$;

REVOKE ALL ON public.founding_client_config FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.founding_client_config TO anon, authenticated;
GRANT ALL ON public.founding_client_config TO service_role;
CREATE POLICY founding_client_config_public_read
  ON public.founding_client_config
  FOR SELECT
  TO anon, authenticated
  USING (true);

REVOKE ALL ON public.founding_client_applications FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.founding_client_applications TO service_role;

INSERT INTO public.founding_client_config (is_active, total_spots)
VALUES (true, 10)
ON CONFLICT DO NOTHING;
